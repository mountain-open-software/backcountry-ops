import { test, expect } from '@playwright/test';
test('local workflows persist, organizations are scoped, and app reloads offline', async ({ page, context }) => {
  const errors = [];
  const remote = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (!r.url().startsWith('http://localhost:4173') && !r.url().startsWith('blob:')) remote.push(r.url()); });
  await page.goto('/');
  await expect(page.getByLabel('Trip name')).toBeVisible();
  await page.getByLabel('Trip name').fill('Ridge traverse');
  await page.getByRole('button', { name: 'Save trip', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Ridge traverse' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Ridge traverse' })).toBeVisible();
  await page.getByText('Local workspace & backups', { exact: true }).click();
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Mountain team');
  await page.getByRole('button', { name: 'Add', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Ridge traverse' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Daily process' }).click();
  await page.getByLabel('Daily briefing title').fill('Morning review');
  await page.getByRole('button', { name: 'Save daily record' }).click();
  await expect(page.getByRole('heading', { name: 'Morning review' })).toBeVisible();
  await page.getByRole('button', { name: 'Observation reporting' }).click();
  await page.getByLabel('Observation title').fill('Fresh snow');
  await page.getByRole('button', { name: 'Save observation' }).click();
  await expect(page.getByRole('heading', { name: 'Fresh snow' })).toBeVisible();
  await page.getByLabel('Organization', { exact: true }).selectOption('org-personal');
  await expect(page.getByRole('heading', { name: 'Fresh snow' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Trip planning' }).click();
  await expect(page.getByRole('heading', { name: 'Ridge traverse' })).toBeVisible();
  await page.evaluate(async () => { await navigator.serviceWorker.ready; if (!navigator.serviceWorker.controller) await new Promise(resolve => navigator.serviceWorker.addEventListener('controllerchange', resolve, { once: true })); });
  await context.setOffline(true);
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Ridge traverse' })).toBeVisible();
  await page.getByLabel('Trip name').fill('Offline plan');
  await page.getByRole('button', { name: 'Save trip', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Offline plan' })).toBeVisible();
  expect(errors).toEqual([]);
  expect(remote).toEqual([]);
});
